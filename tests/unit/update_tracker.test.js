expect("returns 1 when first version is greater (26.02 > 26.01)", function() {
  assert.strictEqual(compareVersions("26.02", "26.01"), 1);
});

// CRITICAL EDGE CASE: numeric comparison (not lexicographic)
// Lexicographic: "9" > "10" (wrong). Numeric: 9 < 10 (correct).
expect("returns -1 when 9.0 < 10.0 (numeric, not lexicographic)", function() {
  assert.strictEqual(compareVersions("9.0", "10.0"), -1);
});

expect("returns 0 for identical multi-part versions", function() {
  assert.strictEqual(compareVersions("11.0.31.11", "11.0.31.11"), 0);
});

expect("returns 1 for multi-part where later segment differs (2.35.9.0 > 2.35.8.0)", function() {
  assert.strictEqual(compareVersions("2.35.9.0", "2.35.8.0"), 1);
});

expect("returns -1 for single-digit major where b is larger (1.0 < 2.0)", function() {
  assert.strictEqual(compareVersions("1.0", "2.0"), -1);
});

