// Source: fixlet_modifier.ojo lines 86-92 / fixlet_dispatcher.ojo lines 69-75
function htmlEscape(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// Source: RESEARCH.md Pattern 2 (lines 262-268)
// CRITICAL: regex is / v\d[\d.]+/g — ONE-or-more [\d.]+ after first digit.
// This preserves product-family tokens like "v2" in "AWS Command Line Interface v2".
function stripVersion(name) {
  return String(name).replace(/ v\d[\d.]+/g, "");
}

// Source: RESEARCH.md Pattern 2 (lines 271-273)
function extractVersion(name) {
  var m = / v(\d[\d.]+)/.exec(name);
  return m ? m[1] : "";
}

// Source: RESEARCH.md Pattern 2 (lines 276-290)
// Segment-by-segment numeric comparison. Returns 1 if a > b, -1 if a < b, 0 if equal.
// parseInt (base 10) prevents lexicographic failure on "9.0" vs "10.0".
function compareVersions(a, b) {
  var pa = a.split("."), pb = b.split(".");
  var len = Math.max(pa.length, pb.length);
  var i, na, nb;
  for (i = 0; i < len; i++) {
    na = parseInt(pa[i] || "0", 10) || 0;
    nb = parseInt(pb[i] || "0", 10) || 0;
    if (na > nb) { return 1; }
    if (na < nb) { return -1; }
  }
  return 0;
}

// Source: RESEARCH.md Code Examples (lines 851-861)
// D-16: prefer old portal fixlet's native <Category>; fall back to CSV lookup.
function lookupCategory(productKey, portalCategory) {
  if (portalCategory && portalCategory !== "") { return portalCategory; }
  if (typeof CATEGORY_MAP !== "undefined" && CATEGORY_MAP[productKey]) {
    return CATEGORY_MAP[productKey];
  }
  return "";
}

// Source: RESEARCH.md Pattern 6 (lines 436-491)
// D-06: show all newer versions (not just latest).
// D-07: show all source-site matches (no deduplication).
function buildScanResults(portalItems, sourceItems) {
  // Build portal map keyed by version-stripped product name
  var portalMap = {};
  var i, key, pItem;
  for (i = 0; i < portalItems.length; i++) {
    pItem = portalItems[i];
    key = stripVersion(pItem.name);
    if (!portalMap[key]) { portalMap[key] = []; }
    portalMap[key].push(pItem);
  }

  var updates  = [];
  var arrivals = [];

  for (i = 0; i < sourceItems.length; i++) {
    var sItem = sourceItems[i];
    var sKey  = stripVersion(sItem.name);
    var sVer  = extractVersion(sItem.name);

    if (portalMap[sKey]) {
      // Matching portal product found — report if source version is newer
      var j, pMatch;
      for (j = 0; j < portalMap[sKey].length; j++) {
        pMatch = portalMap[sKey][j];
        var pVer = extractVersion(pMatch.name);
        if (compareVersions(sVer, pVer) > 0) {
          updates.push({
            portalId:       pMatch.id,
            portalName:     pMatch.name,
            portalCategory: pMatch.category,
            portalRoles:    pMatch.roles,
            sourceId:       sItem.id,
            sourceName:     sItem.name,
            sourceSiteName: sItem.siteName,
            sourceSiteType: sItem.siteType,
            productKey:     sKey
          });
        }
      }
    } else {
      // No matching portal product — report as New Arrival with suggested category
      var suggested = (typeof CATEGORY_MAP !== "undefined" && CATEGORY_MAP[sKey]) || "";
      arrivals.push({
        sourceId:          sItem.id,
        sourceName:        sItem.name,
        sourceSiteName:    sItem.siteName,
        sourceSiteType:    sItem.siteType,
        productKey:        sKey,
        suggestedCategory: suggested
      });
    }
  }

  return { updates: updates, arrivals: arrivals };
}

