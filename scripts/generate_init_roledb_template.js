// generate_init_roledb_template.js -- v1.0.0
//
// Regenerates the INIT_ROLEDB_TEMPLATE block inside
// "Existing Dashboards/fixlet_role_manager.ojo" from bes/Init-RoleDb.bes
// (the source of truth). Never hand-edit the generated block -- edit the .bes
// and re-run:
//
//   node scripts/generate_init_roledb_template.js
//
// The block sits between the BEGIN/END GENERATED marker lines below. Strings are
// emitted as ASCII-only ES5 literals (non-ASCII -> \uXXXX) so the dashboard
// stays IE-engine safe, and the script refuses to emit anything that would break
// the .ojo's own wrapper: "]]>" (ends the Head CDATA), "</script" (ends the
// <script> block) or "<?relevance" (the console would pre-evaluate it).
"use strict";

var fs   = require("fs");
var path = require("path");

var ROOT     = path.join(__dirname, "..");
var BES_PATH = path.join(ROOT, "bes", "Init-RoleDb.bes");
var OJO_PATH = path.join(ROOT, "Existing Dashboards", "fixlet_role_manager.ojo");

var BEGIN = "// BEGIN GENERATED INIT_ROLEDB_TEMPLATE";
var END   = "// END GENERATED INIT_ROLEDB_TEMPLATE";

function cdata(src, tag){
  var re = new RegExp("<" + tag + "(?:\\s[^>]*)?><!\\[CDATA\\[([\\s\\S]*?)\\]\\]></" + tag + ">", "g");
  var out = [], m;
  while((m = re.exec(src)) !== null){ out.push(m[1]); }
  return out;
}
function plain(src, tag){
  var m = new RegExp("<" + tag + ">([^<]*)</" + tag + ">").exec(src);
  return m ? m[1] : "";
}
function lit(s){
  var j = JSON.stringify(String(s));
  return j.replace(/[^\x20-\x7e]/g, function(c){
    return "\\u" + ("0000" + c.charCodeAt(0).toString(16)).slice(-4);
  });
}
function assertSafe(label, s){
  ["]]>", "</script", "<?relevance"].forEach(function(bad){
    if(String(s).toLowerCase().indexOf(bad) >= 0){
      throw new Error(label + " contains forbidden sequence " + JSON.stringify(bad));
    }
  });
}

var bes = fs.readFileSync(BES_PATH, "utf8").replace(/\r\n/g, "\n");

var title        = plain(bes, "Title");
var descriptions = cdata(bes, "Description");
var relevances   = cdata(bes, "Relevance");
var actionScript = cdata(bes, "ActionScript")[0];
if(!title || descriptions.length !== 1 || relevances.length < 1 || !actionScript){
  throw new Error("bes/Init-RoleDb.bes is missing Title/Description/Relevance/ActionScript");
}
if((actionScript.match(/__PREFETCH_PORT__/g) || []).length < 1){
  throw new Error("ActionScript has no __PREFETCH_PORT__ token");
}
[["title", title], ["description", descriptions[0]], ["actionScript", actionScript]]
  .concat(relevances.map(function(r, i){ return ["relevance " + i, r]; }))
  .forEach(function(p){ assertSafe(p[0], p[1]); });

var lines = actionScript.split("\n");
var block = [];
block.push(BEGIN);
block.push("// Generated by scripts/generate_init_roledb_template.js from bes/Init-RoleDb.bes.");
block.push("// DO NOT HAND-EDIT -- edit the .bes and re-run the generator.");
block.push("var INIT_ROLEDB_ACTIONSCRIPT_LINES = [");
block.push(lines.map(function(l){ return "  " + lit(l); }).join(",\n"));
block.push("];");
block.push("var INIT_ROLEDB_TEMPLATE = {");
block.push("  title: " + lit(title) + ",");
block.push("  description: " + lit(descriptions[0]) + ",");
block.push("  relevances: [" + relevances.map(lit).join(", ") + "],");
block.push("  category: " + lit(plain(bes, "Category")) + ",");
block.push("  source: " + lit(plain(bes, "Source")) + ",");
block.push("  sourceReleaseDate: " + lit(plain(bes, "SourceReleaseDate")) + ",");
block.push("  mimeFields: [ { name: \"x-fixlet-modification-time\", value: " +
  lit(plain(bes.substring(bes.indexOf("<MIMEField>")), "Value")) + " } ],");
block.push("  domain: " + lit(plain(bes, "Domain")) + ",");
block.push("  actionDescription: { preLink: " + lit(plain(bes, "PreLink")) +
  ", link: " + lit(plain(bes, "Link")) + ", postLink: " + lit(plain(bes, "PostLink")) + " },");
block.push("  actionScript: INIT_ROLEDB_ACTIONSCRIPT_LINES.join('\\n')");
block.push("};");
block.push(END);
var generated = block.join("\n");

var ojoRaw = fs.readFileSync(OJO_PATH, "utf8");
var eol    = ojoRaw.indexOf("\r\n") >= 0 ? "\r\n" : "\n";
var b = ojoRaw.indexOf(BEGIN), e = ojoRaw.indexOf(END);
if(b < 0 || e < 0 || e < b){ throw new Error("generated-block markers not found in fixlet_role_manager.ojo"); }
var updated = ojoRaw.substring(0, b) + generated.replace(/\n/g, eol) + ojoRaw.substring(e + END.length);
fs.writeFileSync(OJO_PATH, updated, "utf8");
console.log("INIT_ROLEDB_TEMPLATE regenerated: " + lines.length + " ActionScript lines, title " + JSON.stringify(title));
